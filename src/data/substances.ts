const DEFAULT_CONTAINER: Record<State, Container> = {
  powder: 'dish',
  crystals: 'dish',
  liquid: 'beaker',
  gel: 'jar',
  gas: 'canister',
  metal: 'dish',
  chunk: 'dish',
};

interface Extra {
  toxic?: 0 | 1 | 2 | 3;
  flammable?: boolean;
  fizzy?: boolean;
  smoky?: boolean;
  glow?: boolean;
  opacity?: number;
  fictional?: boolean;
  container?: Container;
}

function S(
  id: string,
  name: string,
  formula: string,
  state: State,
  color: string,
  look: string,
  props: Partial<SubstanceProps> & { density: number; mass: number },
  fact: string,
  extra: Extra = {},
): Substance {
  return {
    id,
    name,
    formula,
    state,
    color,
    look,
    container: extra.container ?? DEFAULT_CONTAINER[state],
    props: { ...BASE, ...props },
    toxic: extra.toxic ?? 0,
    flammable: extra.flammable ?? false,
    fizzy: extra.fizzy,
    smoky: extra.smoky,
    glow: extra.glow,
    opacity: extra.opacity,
    fictional: extra.fictional,
    fact,
  };
}

